import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
const root = new URL('../', import.meta.url);
const bundle = async (entry, globalName) => (await build({
  absWorkingDir: fileURLToPath(root), entryPoints: [entry], bundle: true,
  write: false, format: 'iife', globalName, platform: 'browser', minify: true,
  target: ['chrome100', 'safari15'],
  define: { 'import.meta.url': JSON.stringify('https://islasafe.local/maplibre-gl.mjs') },
})).outputFiles[0].text;
const script = await bundle('node_modules/maplibre-gl/dist/maplibre-gl.mjs', 'maplibregl');
const worker = await bundle('node_modules/maplibre-gl/dist/maplibre-gl-worker.mjs');
const css = await readFile(new URL('node_modules/maplibre-gl/dist/maplibre-gl.css', root), 'utf8');
const license = await readFile(new URL('node_modules/maplibre-gl/LICENSE.txt', root), 'utf8');
await writeFile(new URL('src/lib/maplibreAssets.ts', root),
  `// Generated by scripts/update-map-assets.mjs from MapLibre GL JS 6.10.0 (BSD-3-Clause).\n// See maplibre.LICENSE.txt. Bundled locally; no remote JavaScript needed.\nexport const maplibreScript: string = ${JSON.stringify(script)};\nexport const maplibreWorker: string = ${JSON.stringify(worker)};\nexport const maplibreCss: string = ${JSON.stringify(css)};\n`);
await writeFile(new URL('src/lib/maplibre.LICENSE.txt', root), license);
